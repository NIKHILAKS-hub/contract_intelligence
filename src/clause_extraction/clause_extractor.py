# --------------------------------------------------

if __name__ == "__main__":

    print("=" * 70)
    print("CONTRACT CLAUSE EXTRACTOR")
    print("=" * 70)

    file_path = input(
        "\nEnter the path of the extracted TXT file: "
    ).strip()

    try:

        # Load contract
        text = load_contract_text(file_path)

        print(
            f"\nLoaded contract text: "
            f"{len(text)} characters"
        )

        # Extract clauses
        clauses = extract_clauses(text)

        print(
            f"\nNumber of clauses extracted: "
            f"{len(clauses)}"
        )

        # Display
        print_clauses(clauses)

        # Save JSON
        output_path = os.path.join(
            "data",
            "contracts",
            "extracted_clauses.json"
        )

        save_clauses(
            clauses,
            output_path
        )

        print("\nClauses saved to:")
        print(output_path)

        print("\n" + "=" * 70)
        print("CLAUSE EXTRACTION FINISHED")
        print("=" * 70)

    except Exception as e:

        print("\nERROR:")
        print(e)